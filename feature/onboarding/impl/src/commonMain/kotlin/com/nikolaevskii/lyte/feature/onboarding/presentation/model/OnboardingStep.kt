package com.nikolaevskii.lyte.feature.onboarding.presentation.model

/**
 * Шаги тура (кадры 0.1–0.4). Каждый — статичная **реплика** экрана из компонентов дизайн-системы, а
 * не сам экран: подсветка поверх живых экранов требовала бы контракта якорей, который ломается молча
 * при их рефакторинге (решение 8 роадмапа `design-v2`). Цена реплики — риск разойтись с оригиналом;
 * она принята сознательно и проверяется глазами по двум кадрам в одном диффе.
 *
 * Порядок здесь и есть порядок тура: он же задаёт номер шага в точках-пейджере.
 */
enum class OnboardingStep {

    /** Кадр 0.1: лендинг трекера, подсвечена кнопка «Начать». */
    Start,

    /** Кадр 0.2: карточка подхода, подсвечены степперы повторов и веса. */
    Stepper,

    /** Кадр 0.3: та же карточка, подсвечены «Готово» и «Пропустить». */
    Commit,

    /** Кадр 0.4: карточка тренировки в истории. */
    History,
    ;

    companion object {

        val ALL: List<OnboardingStep> = entries
    }
}
