package com.nikolaevskii.lyte.core.workout.data.mapper

/**
 * Неразрывный пробел (U+00A0). Пользователь его не набирает осознанно — его подставляют
 * клавиатуры (в том числе штатная iOS) вместо обычного при автозамене.
 */
private const val NON_BREAKING_SPACE = '\u00A0'

private const val SPACE = ' '

/**
 * Приводит название упражнения к виду, в котором лежит колонка `name_normalized` и в котором
 * приходит поисковый запрос: нижний регистр плюс неразрывный пробел, заменённый обычным.
 *
 * **Одна функция на оба конца сравнения намеренно.** Поиск матчит `name_normalized LIKE`, поэтому
 * стороны обязаны нормализоваться одинаково: неразрывный пробел внутри имени не потерял бы
 * упражнение (оно остаётся доступно пустым запросом, другой подстрокой и по id), но запрос,
 * перекрывающий именно эту позицию, перестал бы находить — деградация поиска, которую нечем
 * заметить, кроме жалобы.
 */
internal fun String.normalizedForSearch(): String = lowercase().replace(NON_BREAKING_SPACE, SPACE)
