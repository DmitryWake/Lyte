package com.nikolaevskii.lyte.core.design.format

import kotlin.math.pow
import kotlin.math.round

/** Дробная часть отделяется запятой: русская типографская норма, она же правило контента v2. */
private const val DECIMAL_SEPARATOR = ','

/**
 * Сотые — предел точности веса во всём приложении: столько же знаков принимает ручной ввод степпера
 * и столько же оставляет его шаг ±. Всё, что точнее, до пользователя не доходит ни одним путём.
 */
internal const val WeightFractionDigits = 2

/**
 * Множитель округления — десять в степени [WeightFractionDigits]. Выводится из константы, а не
 * пишется числом: иначе смена точности на три знака приняла бы «62,125» на вводе и молча срезала
 * его до сотых, а причину пришлось бы искать в двух несвязанных местах.
 */
private val WeightRoundingScale: Double = 10.0.pow(WeightFractionDigits)

/**
 * Единый формат числа веса: целое — без дробной части («60», а не «60.0»), дробное — с запятой и
 * округлением до [WeightFractionDigits] знаков («62,5»). Округление — «к ближайшему чётному» из
 * [round], поэтому ровно половина уходит вниз: `0,125` → «0,12». Из степпера недостижимо (ввод уже
 * ограничен сотыми), но функция публичная и принимает любой `Double`.
 *
 * Одна реализация на **все** места, где вес показывается: значение подхода, дельта в деталях сессии
 * и само поле степпера. Второй форматтер того же числа расходится с первым молча: на `62.4999`
 * подпись над степпером печатала «62.4999», а сам степпер под ней — «62.5», и компилятор такое
 * не ловит.
 */
fun formatWeight(weight: Double): String {
    val rounded = roundToWeightPrecision(weight)
    val asLong = rounded.toLong()
    return if (rounded == asLong.toDouble()) {
        asLong.toString()
    } else {
        rounded.toString().replace('.', DECIMAL_SEPARATOR)
    }
}

/**
 * Округление значения веса до той же точности, с какой оно показывается. Живёт рядом с форматом
 * намеренно: если значение округлять по одному правилу, а печатать по другому, степпер начнёт
 * показывать не то, что отдал наружу.
 */
internal fun roundToWeightPrecision(value: Double): Double =
    round(value * WeightRoundingScale) / WeightRoundingScale
