package com.nikolaevskii.lyte.core.design.component.progress

/**
 * Исход одного подхода относительно цели. Общий словарь всей системы: одно и то же событие обязано
 * выглядеть одинаково и в треке сводки, и в строке подхода на экране тренировки, и в деталях сессии.
 *
 * В [LyteProgressTrack] тон кодируется **высотой сегмента, а не только цветом**: пять состояний
 * невозможно различить оттенком на пятипиксельной полоске (два зелёных — «попал» и «превысил» —
 * сливаются), а легенда убила бы саму идею беглого взгляда.
 */
enum class LyteProgressTone {

    /** Превысил цель — сегмент во всю высоту. */
    Positive,

    /** Попал точно в цель — сегмент по средней линии. */
    Met,

    /** Недобрал до цели — короткий сегмент. */
    Negative,

    /** Подход пропущен — полая обводка. */
    Skipped,

    /** Подход ещё впереди — едва заметная риска. */
    Todo,
}
