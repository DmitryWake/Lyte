#!/bin/sh
# PreToolUse на Bash: не даёт закоммитить эталоны скриншотов.
#
# CLAUDE.md § «Скриншот-тесты»: эталоны генерирует только джоба screenshots в CI — на macOS рендер
# отличается субпиксельно. Локальный recordRoborazzi* нужен, чтобы посмотреть глазами, и его
# результат положено откатывать перед коммитом.
#
# Проверяем саму команду, а не всё тело события: иначе блокировалась бы любая команда, где фраза
# просто упоминается. Поле `if` в настройках не подходит — оно матчит команду с начала строки, и
# составное `git add -A && git commit -m …` мимо него проходит.
#
# Проверяются и staged, и просто изменённые в рабочем дереве PNG: грязный эталон на момент коммита
# в любом случае положено откатить. Команда отката (`git checkout -- …`) под блокировку не попадает —
# в ней нет `git commit`, так что тупика не возникает.
#
# Выход 2 блокирует вызов, stderr приходит модели как причина отказа.

set -u

cmd=$("$(dirname "$0")/lib-extract-command.sh")

# вызов, а не упоминание: в начале команды или сразу после разделителя
printf '%s' "$cmd" | grep -Eq '(^|[;&|(]|&&|\|\|)[[:space:]]*git[[:space:]]+commit' || exit 0

dirty=$(
    { git diff --cached --name-only 2>/dev/null; git diff --name-only 2>/dev/null; } \
        | grep -E '/screenshots/.*\.png$' \
        | sort -u
)

[ -z "$dirty" ] && exit 0

printf 'Эталоны скриншотов изменены локально — их генерирует только CI (CLAUDE.md § «Скриншот-тесты»).\n' >&2
printf 'Откати перед коммитом:\n' >&2
printf "  git checkout -- '*/screenshots/*'\n" >&2
printf 'и удали новые PNG, если появились. Затронуты:\n' >&2
printf '%s\n' "$dirty" | sed 's/^/  /' >&2
exit 2
