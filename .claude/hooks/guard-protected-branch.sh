#!/bin/sh
# PreToolUse на Bash: не даёт запушить напрямую в master или development.
#
# CLAUDE.md § Git Flow: в защищённые ветки попадают только через pull request. Мерж PR автопилот
# делает через GitHub API (mcp__github__merge_pull_request), а не пушем, поэтому запрет ему не мешает.
#
# Разбираем именно команду из payload, а не всё тело события: иначе блокировалась бы любая команда,
# где фраза просто упоминается. Поле `if` в настройках тоже не подходит — оно матчит команду с начала
# строки, и составное `git add -A && …` мимо него проходит.
#
# Имя ветки ищем ТОЛЬКО в аргументах самого вызова, до ближайшего разделителя. Иначе `.*` дотягивался
# бы до конца команды и ловил слово «development» где угодно дальше — например в тексте
# коммит-сообщения, переданного тут же через heredoc.
#
# Известный перекос: команда, которая ЦИТИРУЕТ настоящий вызов пуша в защищённую ветку — тест этого
# же хука, кусок документации — будет заблокирована наравне с настоящим вызовом. Отличить цитату от
# вызова можно только полноценным разбором шелла, и оно того не стоит: цена ложного срабатывания —
# отказ с внятным текстом, цена пропуска — сломанная защищённая ветка. Тесты собирают такие строки
# из кусков, чтобы литерал не встречался целиком.
#
# Выход 2 блокирует вызов, stderr приходит модели как причина отказа.

set -u

PROTECTED='master|development'
cmd=$("$(dirname "$0")/lib-extract-command.sh")

# вызовы push: от `git push` до ближайшего разделителя команд
pushes=$(printf '%s' "$cmd" | grep -oE '(^|[;&|(])[[:space:]]*git[[:space:]]+push[^;&|]*')

[ -z "$pushes" ] && exit 0

blocked=''
if printf '%s' "$pushes" | grep -Eq "($PROTECTED)"; then
    blocked='ветка названа в аргументах push'
fi

branch=$(git rev-parse --abbrev-ref HEAD 2>/dev/null || echo '')
if printf '%s\n' "$branch" | grep -Eq "^($PROTECTED)$"; then
    blocked="текущая ветка — $branch"
fi

[ -z "$blocked" ] && exit 0

cat >&2 <<MSG
Прямой push в защищённую ветку запрещён ($blocked).
CLAUDE.md § Git Flow: master и development принимают изменения только через pull request.
Заведи фича-ветку и открой PR; мерж PR идёт через GitHub API, а не пушем.
MSG
exit 2
