#!/bin/sh
# Достаёт tool_input.command из тела события хука (JSON на stdin) и печатает в stdout.
#
# jq используется, если он есть; иначе — sed. Без этого разбора хуки искали бы подстроку во всём
# теле события, и тогда команда, которая просто УПОМИНАЕТ запретную фразу (grep по докам, echo,
# правка самого хука), блокировалась бы наравне с настоящим вызовом.

set -u

payload=$(cat)

if command -v jq >/dev/null 2>&1; then
    printf '%s' "$payload" | jq -r '.tool_input.command // empty' 2>/dev/null && exit 0
fi

# Запасной разбор: от "command":" до первой неэкранированной кавычки, затем разэкранирование.
printf '%s' "$payload" \
    | sed -n 's/.*"command"[[:space:]]*:[[:space:]]*"\(\([^"\\]\|\\.\)*\)".*/\1/p' \
    | sed 's/\\"/"/g; s/\\\\/\\/g; s/\\n/ /g; s/\\t/ /g'
